const DICTS = { en: EN, ar: AR };
let current = 'en';

export function setLang(lang) {
  current = DICTS[lang] ? lang : 'en';
  if (typeof document !== 'undefined') {
    document.documentElement.lang = current;
    document.documentElement.dir = current === 'ar' ? 'rtl' : 'ltr';
    document.body && document.body.classList.toggle('rtl', current === 'ar');
  }
  return current;
}

export function getLang() { return current; }
export function isRTL() { return current === 'ar'; }
export function toggleLang() { return setLang(current === 'ar' ? 'en' : 'ar'); }

/** t('cash') -> 'Cash' / 'النقد'  (falls back to English, then to the key) */
export function t(key) {
  const d = DICTS[current];
  return (d && d[key]) || EN[key] || key;
}

/** Translate a game id ("g01") into its display name. */
export function gameName(id) { return t(id); }
/** Translate a game id into its controls hint. */
export function gameHowTo(id) { return t(id + '_how'); }

/** Bind every [data-i18n] element in a root. */
export function applyI18n(root = document) {
  root.querySelectorAll('[data-i18n]').forEach((el) => {
    el.textContent = t(el.getAttribute('data-i18n'));
  });
  root.querySelectorAll('[data-i18n-ph]').forEach((el) => {
    el.setAttribute('placeholder', t(el.getAttribute('data-i18n-ph')));
  });
}